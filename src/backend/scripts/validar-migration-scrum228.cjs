async function esperarErroSql(trx, codigoEsperado, acao) {
  await trx.raw('SAVEPOINT sp_teste_negativo');
  try {
    await acao();
    return false;
  } catch (e) {
    await trx.raw('ROLLBACK TO SAVEPOINT sp_teste_negativo');
    await trx.raw('RELEASE SAVEPOINT sp_teste_negativo');
    return e && e.code === codigoEsperado;
  }
}

async function criarBaseIsolada(trx, schema) {
  await trx.raw('CREATE SCHEMA ??', [schema]);
  await trx.raw('SET LOCAL search_path TO ??', [schema]);

  await trx.raw(`
    CREATE TABLE usuarios (
      id SERIAL PRIMARY KEY,
      nome VARCHAR(255) NOT NULL,
      email VARCHAR(255) NOT NULL UNIQUE,
      senha VARCHAR(255) NOT NULL,
      tipo_usuario VARCHAR(50) NOT NULL,
      perfil VARCHAR(50) NOT NULL,
      ativo BOOLEAN NOT NULL DEFAULT true,
      versao_sessao INTEGER NOT NULL DEFAULT 1
    );

    CREATE TABLE notificacoes (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
      tipo VARCHAR(80) NOT NULL,
      categoria VARCHAR(60) NOT NULL DEFAULT 'GERAL',
      titulo VARCHAR(160) NOT NULL,
      mensagem TEXT NOT NULL,
      severidade VARCHAR(20) NOT NULL DEFAULT 'INFO',
      operacao VARCHAR(20) NOT NULL,
      referencia_tipo VARCHAR(50) NULL,
      referencia_id INTEGER NULL,
      url_destino VARCHAR(255) NOT NULL,
      chave_idempotencia VARCHAR(190) NOT NULL,
      lida_em TIMESTAMPTZ NULL,
      criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT uq_notificacoes_usuario_chave_idempotencia UNIQUE (usuario_id, chave_idempotencia)
    );

    INSERT INTO usuarios (id, nome, email, senha, tipo_usuario, perfil)
    VALUES
      (1, 'Solicitante A', 'solicitante.a@exemplo.invalid', 'hash', 'SOLICITANTE', 'SOLICITANTE'),
      (2, 'Motorista B', 'motorista.b@exemplo.invalid', 'hash', 'MOTORISTA', 'MOTORISTA_FROTA');
    SELECT setval(pg_get_serial_sequence('usuarios', 'id'), 2, true);
  `);
}

async function executarValidacaoCompletaScrum228() {
  const configMigration = knexConfig.criarConfigKnex({
    ...process.env,
    DB_ROLE: 'migration',
  });
  const db = knex(configMigration);
  const relatorio = [];

  try {
    // 1. Bloqueio quando tabela base usuarios nao existe no schema
    const schemaSemBase = `val228_sem_base_${Date.now()}`;
    await db
      .transaction(async (trx) => {
        await trx.raw('CREATE SCHEMA ??', [schemaSemBase]);
        await trx.raw('SET LOCAL search_path TO ??', [schemaSemBase]);

        let bloqueouSemBase = false;
        try {
          await migrationScrum228.up(trx);
        } catch (e) {
          bloqueouSemBase = /tabela base usuarios ausente/i.test(e.message);
        }
        if (!bloqueouSemBase) {
          throw new Error('Migration up deveria ter bloqueado schema sem tabela base usuarios.');
        }
        throw new Error('ROLLBACK_ISOLADO');
      })
      .catch((e) => {
        if (e.message !== 'ROLLBACK_ISOLADO') throw e;
      });

    // 2. Bloqueio de estrutura preexistente incompativel no UP
    const schemaIncomp = `val228_inc_${Date.now()}`;
    await db
      .transaction(async (trx) => {
        await criarBaseIsolada(trx, schemaIncomp);
        await trx.raw(`
          CREATE TABLE notificacao_outbox (
            id SERIAL PRIMARY KEY,
            usuario_id INTEGER NOT NULL,
            payload_push TEXT NOT NULL
          )
        `);

        let bloqueouIncompativel = false;
        try {
          await migrationScrum228.up(trx);
        } catch (e) {
          bloqueouIncompativel = /Estrutura incompativel em notificacao_outbox/i.test(e.message);
        }
        if (!bloqueouIncompativel) {
          throw new Error(
            'Migration up deveria ter rejeitado tabela notificacao_outbox preexistente incompativel.'
          );
        }
        throw new Error('ROLLBACK_ISOLADO');
      })
      .catch((e) => {
        if (e.message !== 'ROLLBACK_ISOLADO') throw e;
      });

    relatorio.push(
      '1. Bloqueio de ausencia de tabela base e estruturas preexistentes incompativeis no up: OK'
    );

    // 3. Ciclo completo: UP -> Atomicidade In-App + Outbox -> Deduplicacao vs Reprogramacao -> Disputa/Lease e Falha Parcial -> Expurgo -> Down protegido -> Re-UP
    const schemaCiclo = `val228_ciclo_${Date.now()}`;
    await db
      .transaction(async (trx) => {
        await criarBaseIsolada(trx, schemaCiclo);
        await migrationScrum228.up(trx);
        relatorio.push(
          '2. Aplicacao limpa da migration SCRUM-228 (up) e validacao de catalogo: OK'
        );

        // 3.1 Atomicidade transacional (NF-06): rollback da operacao de dominio desfaz In-App e Outbox juntos
        await trx.raw('SAVEPOINT sp_operacao_revertida');
        const [notifRevertida] = await trx('notificacoes')
          .insert({
            usuario_id: 2,
            tipo: 'A5_VIAGEM_AGENDADA',
            categoria: 'VIAGENS',
            titulo: 'Nova viagem agendada',
            mensagem: 'Viagem #50 agendada para voce.',
            severidade: 'INFO',
            operacao: 'ADMINISTRATIVA',
            referencia_tipo: 'VIAGEM_FROTA',
            referencia_id: 50,
            url_destino: '/viagens',
            chave_idempotencia: 'A5:VIAGEM_FROTA:50:v1',
          })
          .returning('*');

        await trx('notificacao_outbox').insert({
          notificacao_id: notifRevertida.id,
          usuario_id: 2,
          evento_tipo: 'A5_VIAGEM_AGENDADA',
          categoria: 'VIAGENS',
          operacao: 'ADMINISTRATIVA',
          referencia_tipo: 'VIAGEM_FROTA',
          referencia_id: 50,
          ocorrencia_versao: 'viagem:50:agendada:v1',
          chave_idempotencia: 'A5:VIAGEM_FROTA:50:v1',
          canal: 'WEB_PUSH',
          payload_push: {
            titulo: 'Nova viagem agendada',
            corpo: 'Consulte sua escala no sistema FSPH.',
            url_destino: '/viagens',
            tag: 'viagem-50',
          },
        });

        await trx.raw('ROLLBACK TO SAVEPOINT sp_operacao_revertida');
        await trx.raw('RELEASE SAVEPOINT sp_operacao_revertida');

        const qtdInAppAposRollback = await trx('notificacoes').count({ total: '*' }).first();
        const qtdOutboxAposRollback = await trx('notificacao_outbox').count({ total: '*' }).first();
        if (
          Number(qtdInAppAposRollback?.total || 0) !== 0 ||
          Number(qtdOutboxAposRollback?.total || 0) !== 0
        ) {
          throw new Error(
            'Falha de atomicidade (NF-06): rollback da operacao deixou residuos em notificacoes ou notificacao_outbox.'
          );
        }

        relatorio.push(
          '3. Atomicidade transacional (NF-06): rollback do dominio reverte In-App e Outbox simultaneamente: OK'
        );

        // 3.2 Insercao confirmada + Deduplicacao de retry vs Reprogramacao legitima (NF-08)
        const tsCriacao = new Date('2026-11-24T12:00:00.000Z');
        const [notifConfirmada] = await trx('notificacoes')
          .insert({
            usuario_id: 2,
            tipo: 'A6_VIAGEM_REPROGRAMADA',
            categoria: 'VIAGENS',
            titulo: 'Viagem reprogramada',
            mensagem: 'Horario da viagem #55 alterado para 10:00.',
            severidade: 'ALERTA',
            operacao: 'ADMINISTRATIVA',
            referencia_tipo: 'VIAGEM_FROTA',
            referencia_id: 55,
            url_destino: '/viagens',
            chave_idempotencia: 'A6:VIAGEM_FROTA:55:2026-11-25T10:00Z',
            criado_em: tsCriacao,
          })
          .returning('*');

        const [outboxV1] = await trx('notificacao_outbox')
          .insert({
            notificacao_id: notifConfirmada.id,
            usuario_id: 2,
            evento_tipo: 'A6_VIAGEM_REPROGRAMADA',
            categoria: 'VIAGENS',
            operacao: 'ADMINISTRATIVA',
            referencia_tipo: 'VIAGEM_FROTA',
            referencia_id: 55,
            ocorrencia_versao: 'viagem:55:2026-11-25T10:00Z',
            chave_idempotencia: 'A6:VIAGEM_FROTA:55:2026-11-25T10:00Z',
            canal: 'WEB_PUSH',
            payload_push: {
              titulo: 'Viagem reprogramada',
              corpo: 'Uma viagem atribuida a voce teve o horario atualizado.',
              url_destino: '/viagens',
              tag: 'viagem-55',
            },
            criado_em: tsCriacao,
            atualizado_em: tsCriacao,
          })
          .returning('*');

        // Retry duplicado com mesma chave_idempotencia para o mesmo usuario deve ser bloqueado (23505)
        const bloqueouRetryMesmaChave = await esperarErroSql(trx, '23505', () =>
          trx('notificacao_outbox').insert({
            usuario_id: 2,
            evento_tipo: 'A6_VIAGEM_REPROGRAMADA',
            categoria: 'VIAGENS',
            operacao: 'ADMINISTRATIVA',
            referencia_tipo: 'VIAGEM_FROTA',
            referencia_id: 55,
            ocorrencia_versao: 'viagem:55:outra-versao',
            chave_idempotencia: 'A6:VIAGEM_FROTA:55:2026-11-25T10:00Z',
            canal: 'WEB_PUSH',
          })
        );

        // Retry duplicado com mesma (evento_tipo, usuario_id, canal, ocorrencia_versao) mesmo trocando chave_idempotencia deve ser bloqueado (23505)
        const bloqueouRetryMesmaOcorrencia = await esperarErroSql(trx, '23505', () =>
          trx('notificacao_outbox').insert({
            usuario_id: 2,
            evento_tipo: 'A6_VIAGEM_REPROGRAMADA',
            categoria: 'VIAGENS',
            operacao: 'ADMINISTRATIVA',
            referencia_tipo: 'VIAGEM_FROTA',
            referencia_id: 55,
            ocorrencia_versao: 'viagem:55:2026-11-25T10:00Z',
            chave_idempotencia: 'A6:VIAGEM_FROTA:55:retry-distinto',
            canal: 'WEB_PUSH',
          })
        );

        // Mesmo evento e mesma ocorrencia para OUTRO destinatario (usuario 1 - solicitante) deve ser permitido!
        await trx('notificacao_outbox').insert({
          usuario_id: 1,
          evento_tipo: 'A6_VIAGEM_REPROGRAMADA',
          categoria: 'VIAGENS',
          operacao: 'ADMINISTRATIVA',
          referencia_tipo: 'VIAGEM_FROTA',
          referencia_id: 55,
          ocorrencia_versao: 'viagem:55:2026-11-25T10:00Z',
          chave_idempotencia: 'A6:VIAGEM_FROTA:55:2026-11-25T10:00Z',
          canal: 'WEB_PUSH',
          payload_push: {
            titulo: 'Viagem reprogramada',
            corpo: 'Sua viagem agendada teve o horario atualizado.',
            url_destino: '/solicitacoes',
            tag: 'viagem-55',
          },
          criado_em: tsCriacao,
          atualizado_em: tsCriacao,
        });

        // Reprogramacao legitima para novo horario (nova ocorrencia_versao) para o mesmo motorista (usuario 2) deve ser permitida!
        const [outboxV2] = await trx('notificacao_outbox')
          .insert({
            usuario_id: 2,
            evento_tipo: 'A6_VIAGEM_REPROGRAMADA',
            categoria: 'VIAGENS',
            operacao: 'ADMINISTRATIVA',
            referencia_tipo: 'VIAGEM_FROTA',
            referencia_id: 55,
            ocorrencia_versao: 'viagem:55:2026-11-25T14:00Z',
            chave_idempotencia: 'A6:VIAGEM_FROTA:55:2026-11-25T14:00Z',
            canal: 'WEB_PUSH',
            payload_push: {
              titulo: 'Viagem reprogramada',
              corpo: 'Uma viagem atribuida a voce teve o horario atualizado.',
              url_destino: '/viagens',
              tag: 'viagem-55',
            },
            max_tentativas: 3,
            criado_em: tsCriacao,
            atualizado_em: tsCriacao,
          })
          .returning('*');

        if (!bloqueouRetryMesmaChave || !bloqueouRetryMesmaOcorrencia || !outboxV2?.id) {
          throw new Error(
            'Falha na deduplicacao de retry ou na permissao de reprogramacao legitima (NF-08).'
          );
        }

        relatorio.push(
          '4. Deduplicacao de retries e suporte a reprogramacoes legitimas e multiplos destinatarios (NF-08): OK'
        );

        // 3.3 Testa constraints de processamento, tentativas, payload jsonb e falha parcial com lease
        const bloqueouStatusTerminalSemProcessadoEm = await esperarErroSql(trx, '23514', () =>
          trx('notificacao_outbox')
            .where({ id: outboxV1.id })
            .update({ status: 'ENVIADO', processado_em: null })
        );

        const bloqueouPendenteComProcessadoEm = await esperarErroSql(trx, '23514', () =>
          trx('notificacao_outbox')
            .where({ id: outboxV1.id })
            .update({ status: 'PENDENTE', processado_em: new Date('2026-11-24T12:05:00.000Z') })
        );

        const bloqueouTentativasAcimaDoMaximo = await esperarErroSql(trx, '23514', () =>
          trx('notificacao_outbox').where({ id: outboxV2.id }).update({ tentativas: 4 })
        );

        const bloqueouPayloadArray = await esperarErroSql(trx, '23514', () =>
          trx('notificacao_outbox')
            .where({ id: outboxV1.id })
            .update({ payload_push: JSON.stringify(['invalido']) })
        );

        if (
          !bloqueouStatusTerminalSemProcessadoEm ||
          !bloqueouPendenteComProcessadoEm ||
          !bloqueouTentativasAcimaDoMaximo ||
          !bloqueouPayloadArray
        ) {
          throw new Error('Falha nas constraints de estado, tentativas ou payload_push da outbox.');
        }

        // Simula claim (PROCESSANDO com lease bloqueado_ate), falha parcial (retry 429) e conclusao (ENVIADO / FALHA_DEFINITIVA)
        const tsProcessado = new Date('2026-11-24T12:10:00.000Z');
        await trx('notificacao_outbox')
          .where({ id: outboxV1.id })
          .update({
            status: 'ENVIADO',
            tentativas: 1,
            ultimo_status_http: 201,
            processado_em: tsProcessado,
            atualizado_em: tsProcessado,
          });

        // Simula falha parcial no outboxV2 (429 Too Many Requests -> volta para PENDENTE com backoff)
        await trx('notificacao_outbox')
          .where({ id: outboxV2.id })
          .update({
            status: 'PENDENTE',
            tentativas: 1,
            ultimo_status_http: 429,
            ultimo_erro: 'WEB_PUSH_RATE_LIMIT',
            proxima_execucao_em: new Date('2026-11-24T12:15:00.000Z'),
            bloqueado_ate: null,
          });

        // Depois atinge falha definitiva no outboxV2
        await trx('notificacao_outbox')
          .where({ id: outboxV2.id })
          .update({
            status: 'FALHA_DEFINITIVA',
            tentativas: 3,
            ultimo_status_http: 503,
            ultimo_erro: 'MAX_RETRIES_EXCEEDED',
            processado_em: tsProcessado,
            atualizado_em: tsProcessado,
          });

        // Verifica filtro de expurgo: apenas estados terminais (ENVIADO, FALHA_DEFINITIVA, IGNORADO), preservando o item PENDENTE do usuario 1
        const { rows: elegiveisOutbox } = await trx.raw(
          `SELECT id, status
           FROM notificacao_outbox
           WHERE status IN ('ENVIADO', 'FALHA_DEFINITIVA', 'IGNORADO')
             AND processado_em <= ?::timestamptz
           ORDER BY id ASC`,
          [tsProcessado.toISOString()]
        );

        if (elegiveisOutbox.length !== 2) {
          throw new Error(
            `Filtro de retencao de estados terminais da outbox deveria retornar 2 registros, retornou ${elegiveisOutbox.length}`
          );
        }

        relatorio.push(
          '5. Controle de tentativas, lease de processamento, falha parcial e elegibilidade de expurgo terminal: OK'
        );

        // 3.4 Testa protecao de rollback (down bloqueado com dados) e ciclo down/up limpo
        let bloqueouDownComDados = false;
        try {
          await migrationScrum228.down(trx);
        } catch (e) {
          bloqueouDownComDados =
            /Rollback bloqueado: existem registros em notificacao_outbox/i.test(e.message);
        }
        if (!bloqueouDownComDados) {
          throw new Error(
            'Migration down deveria ter bloqueado rollback com registros em notificacao_outbox.'
          );
        }

        await trx('notificacao_outbox').del();
        await migrationScrum228.down(trx);
        await migrationScrum228.up(trx);

        relatorio.push(
          '6. Protecao contra rollback destrutivo e ciclo completo down -> up idempotente: OK'
        );

        throw new Error('ROLLBACK_ISOLADO');
      })
      .catch((e) => {
        if (e.message !== 'ROLLBACK_ISOLADO') throw e;
      });

    // 4. Verifica estado da role da aplicacao se configurada no ambiente
    const appUser = process.env.POSTGRES_APP_USER;
    if (appUser) {
      const estadoRole = await inspecionarEstadoRole(db, appUser);
      if (estadoRole) {
        validarEstadoMinimoPrivilegio(estadoRole);
        relatorio.push(`7. Validacao de minimo privilegio da role "${appUser}": OK`);
      }
    }

    console.log('=== VALIDACAO MIGRATION SCRUM-228 CONCLUIDA COM SUCESSO ===');
    for (const item of relatorio) {
      console.log(` - ${item}`);
    }
  } finally {
    await db.destroy();
  }
}

